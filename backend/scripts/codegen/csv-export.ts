// Writes the source of src/generated/export.ts: the header and the row order of
// the CSV export (GET /export, task M1-T6, ADR 0017), taken from the
// `x-csv-columns` and `x-csv-item-types` extensions on the `text/csv` media
// type of its 200 response in contracts/openapi.yaml. The backend never
// writes either list by hand. The contract lint (contracts/lib/openapi.mjs,
// checkCsvExport) proves the columns match the exported resources; this
// generator only checks the shape it relies on and fails on anything else.

export class CsvExportGenerationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'CsvExportGenerationError';
  }
}

const CSV_NAME = /^[a-z][a-z0-9_]{0,62}$/;
/** The first column, which names the kind of item of each row (contracts/README.md, CSV export). */
const ITEM_TYPE_COLUMN = 'item_type';

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function fail(message: string): never {
  throw new CsvExportGenerationError(message);
}

function nameList(value: unknown, where: string): string[] {
  if (!Array.isArray(value) || value.length === 0) fail(`${where}: must be a non-empty list`);
  const names: string[] = [];
  for (const entry of value) {
    if (typeof entry !== 'string' || !CSV_NAME.test(entry)) fail(`${where}: every entry must be a snake_case name`);
    if (names.includes(entry)) fail(`${where}: repeats ${entry}`);
    names.push(entry);
  }
  return names;
}

/** The `text/csv` media type object of GET /export's 200 response. */
function exportMediaType(document: unknown): Record<string, unknown> {
  const where = 'paths./export.get.responses.200.content.text/csv';
  if (!isObject(document) || !isObject(document.paths)) fail('paths: missing');
  const path = document.paths['/export'];
  const get = isObject(path) ? path.get : undefined;
  const responses = isObject(get) ? get.responses : undefined;
  const ok = isObject(responses) ? responses['200'] : undefined;
  const content = isObject(ok) ? ok.content : undefined;
  const csv = isObject(content) ? content['text/csv'] : undefined;
  if (!isObject(csv)) fail(`${where}: missing`);
  return csv;
}

/** Returns the TypeScript source of the generated export module. */
export function generateExportSource(document: unknown): string {
  const media = exportMediaType(document);
  const columns = nameList(media['x-csv-columns'], 'x-csv-columns');
  const itemTypes = nameList(media['x-csv-item-types'], 'x-csv-item-types');
  if (columns[0] !== ITEM_TYPE_COLUMN) fail(`x-csv-columns: the first column must be ${ITEM_TYPE_COLUMN}`);

  const list = (values: readonly string[]): string => `[\n${values.map((value) => `  '${value}',`).join('\n')}\n] as const`;
  return [
    '// Generated by backend/scripts/generate-contract.ts from the x-csv-columns and',
    '// x-csv-item-types extensions of GET /export in contracts/openapi.yaml.',
    '// Do not edit. Change the contract, then run `npm run generate` in backend/.',
    '',
    '/** The header row of the CSV export, in order (x-csv-columns). */',
    `export const EXPORT_CSV_COLUMNS = ${list(columns)};`,
    'export type ExportCsvColumn = (typeof EXPORT_CSV_COLUMNS)[number];',
    '',
    '/** The values of the `item_type` column, in row order (x-csv-item-types). */',
    `export const EXPORT_CSV_ITEM_TYPES = ${list(itemTypes)};`,
    'export type ExportCsvItemType = (typeof EXPORT_CSV_ITEM_TYPES)[number];',
    '',
  ].join('\n');
}
