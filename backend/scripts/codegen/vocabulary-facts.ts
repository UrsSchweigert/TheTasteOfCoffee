// Writes the source of src/generated/vocabulary-facts.ts: two facts the nightly
// rebuild needs from the published vocabulary versions and that the API binding
// (generated/vocabulary.ts) does not carry: the grams of each bag size
// (contracts/vocabulary/v<N>/shelf.json) and the country each origin rolls up to
// (bean.json). Written once here so no number or id list is hard-coded in the
// backend (CLAUDE.md, invariant 2). Only published versions are read, each under
// its own version number: a shelf entry or bean is resolved against the version it
// names (an unknown version, id or origin gives `undefined`, never a guess).
import { isPublished, VocabularyGenerationError, type VersionFiles } from './vocabulary.ts';

type JsonObject = Record<string, unknown>;

function isObject(value: unknown): value is JsonObject {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function fail(message: string): never {
  throw new VocabularyGenerationError(message);
}

const ID = /^[a-z][a-z0-9_]*$/;

/** Origin ids that name no place: a blend, "other", "unknown". They roll up to no country and get no ranking (ADR 0035 point 14). The catch-all ids of NON_PARENT_IDS in contracts/lib/vocabulary.mjs without `mixed` (no origin); a test pins that they agree. */
const NON_PLACE_ORIGINS: ReadonlySet<string> = new Set(['blend', 'other', 'unknown']);

function entries(file: unknown, list: string, where: string): JsonObject[] {
  if (!isObject(file)) return [];
  const value = file[list];
  if (!Array.isArray(value)) return [];
  return value.map((entry): JsonObject => (isObject(entry) ? entry : fail(`${where}.${list}: an entry is not an object`)));
}

function idOf(entry: JsonObject, where: string): string {
  const { id } = entry;
  if (typeof id !== 'string' || !ID.test(id)) fail(`${where}: not a snake_case id`);
  return id;
}

/** `{ <bag size id>: grams }` of one version (empty when the version has none). */
function bagSizes(version: VersionFiles): Record<string, number> {
  const result: Record<string, number> = {};
  for (const entry of entries(version.files.shelf, 'bag_sizes', `v${String(version.version)}/shelf.json`)) {
    const id = idOf(entry, 'bag_sizes');
    const { grams } = entry;
    if (typeof grams !== 'number' || !Number.isSafeInteger(grams) || grams <= 0) fail(`bag size ${id}: grams is not a positive integer`);
    if (id in result) fail(`bag size ${id}: repeated`);
    result[id] = grams;
  }
  return result;
}

/** `{ <origin id>: <country id> }`: a country maps to itself, a region to its `country`; blend, other, unknown to nothing. */
function originCountries(version: VersionFiles): Record<string, string> {
  const where = `v${String(version.version)}/bean.json`;
  const list = entries(version.files.bean, 'origins', where);
  const ids = new Set(list.map((entry) => idOf(entry, 'origins')));
  const result: Record<string, string> = {};
  for (const entry of list) {
    const id = idOf(entry, 'origins');
    if (NON_PLACE_ORIGINS.has(id)) continue;
    const { country } = entry;
    if (country === undefined) {
      result[id] = id;
      continue;
    }
    if (typeof country !== 'string' || !ids.has(country) || NON_PLACE_ORIGINS.has(country)) fail(`origin ${id}: country is not an origin of the same list`);
    result[id] = country;
  }
  return result;
}

function emitMap(out: string[], name: string, doc: string, type: string, perVersion: ReadonlyMap<number, Record<string, string | number>>): void {
  out.push(doc);
  out.push(`export const ${name}: Readonly<Record<number, Readonly<Record<string, ${type}>>>> = {`);
  for (const [version, map] of perVersion) {
    out.push(`  ${String(version)}: {`);
    for (const [key, value] of Object.entries(map)) out.push(`    ${key}: ${typeof value === 'number' ? String(value) : `'${value}'`},`);
    out.push('  },');
  }
  out.push('};');
}

/** The generated source for the published versions among `versions`. */
export function generateVocabularyFactsSource(versions: readonly VersionFiles[]): string {
  const published = versions.filter((v) => isPublished(v));
  const grams = new Map<number, Record<string, string | number>>();
  const countries = new Map<number, Record<string, string | number>>();
  for (const version of published) {
    grams.set(version.version, bagSizes(version));
    countries.set(version.version, originCountries(version));
  }
  const out: string[] = [];
  out.push('// Generated by backend/scripts/generate-contract.ts from the published versions in contracts/vocabulary.');
  out.push('// Do not edit. Change the contract, then run `npm run generate` in backend/.');
  out.push('');
  emitMap(out, 'BAG_SIZE_GRAMS', '/** Grams of each bag size id, per vocabulary version (shelf.json). An id or version that is not here has no known size. */', 'number', grams);
  out.push('');
  emitMap(out, 'ORIGIN_COUNTRY', '/** The country each origin id ranks under, per vocabulary version (bean.json): a country maps to itself, a region to its country. blend, other and unknown are not here. */', 'string', countries);
  out.push('');
  return out.join('\n');
}
